-- 酒店经营目标合同：每次调整追加一个版本，旧版本不覆盖。
CREATE TABLE IF NOT EXISTS `hotel_operating_goal_contracts` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `tenant_id` INT UNSIGNED NOT NULL COMMENT '租户ID',
  `hotel_id` INT UNSIGNED NOT NULL COMMENT '宿析酒店ID',
  `version_no` INT UNSIGNED NOT NULL COMMENT '酒店内递增版本号',
  `contract_schema` VARCHAR(50) NOT NULL COMMENT 'hotel_operating_goal.v1',
  `primary_objective` VARCHAR(30) NOT NULL COMMENT 'revenue/profit/cash_flow',
  `primary_metric_key` VARCHAR(80) NOT NULL COMMENT '首要目标指标键',
  `objective_direction` VARCHAR(20) NOT NULL COMMENT 'increase/preserve',
  `guard_metrics_json` JSON NOT NULL COMMENT '保护指标及上下限',
  `operating_constraints_json` JSON NOT NULL COMMENT '最低价、库存、房型、渠道和日期约束',
  `risk_preference` VARCHAR(20) NOT NULL COMMENT 'conservative/balanced/aggressive',
  `operating_phase` VARCHAR(40) NOT NULL COMMENT '当前经营阶段',
  `phase_note` VARCHAR(500) NOT NULL DEFAULT '' COMMENT '阶段补充说明',
  `stop_conditions_json` JSON NOT NULL COMMENT '必须停止的条件',
  `rollback_plan` VARCHAR(1000) NOT NULL COMMENT '停止后的回滚方案',
  `effective_from` DATE NOT NULL COMMENT '合同生效经营日',
  `effective_to` DATE NOT NULL COMMENT '合同截止经营日',
  `version_note` VARCHAR(500) NOT NULL DEFAULT '' COMMENT '本次换版原因',
  `content_digest` CHAR(64) NOT NULL COMMENT '规范化合同SHA-256摘要',
  `created_by` BIGINT UNSIGNED NOT NULL COMMENT '创建人用户ID',
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uniq_hotel_goal_contract_version` (`tenant_id`, `hotel_id`, `version_no`),
  UNIQUE KEY `uniq_hotel_goal_contract_digest` (`tenant_id`, `hotel_id`, `content_digest`),
  KEY `idx_hotel_goal_contract_current` (`tenant_id`, `hotel_id`, `id`),
  KEY `idx_hotel_goal_contract_effective` (`tenant_id`, `hotel_id`, `effective_from`, `effective_to`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='酒店经营目标合同版本账本';

