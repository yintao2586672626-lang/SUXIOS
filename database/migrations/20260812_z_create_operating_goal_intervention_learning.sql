-- 干预学习判定：允许保存 indeterminate，永不把缺失证据补成成功。
CREATE TABLE IF NOT EXISTS `operation_intervention_assessments` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `tenant_id` INT UNSIGNED NOT NULL COMMENT '租户ID',
  `hotel_id` INT UNSIGNED NOT NULL COMMENT '宿析酒店ID',
  `intent_id` BIGINT UNSIGNED NOT NULL COMMENT '运营执行意图ID',
  `task_id` BIGINT UNSIGNED NOT NULL COMMENT '已进入执行链的任务ID',
  `intervention_contract_id` BIGINT UNSIGNED NOT NULL COMMENT '冻结的干预合同ID',
  `assessment_schema` VARCHAR(60) NOT NULL COMMENT 'operation_intervention_assessment.v1',
  `verdict` VARCHAR(20) NOT NULL COMMENT 'supported/contradicted/indeterminate',
  `reason_codes_json` JSON NOT NULL COMMENT '确定性判定理由及缺口',
  `followup_snapshot_json` JSON NOT NULL COMMENT '观察窗结果快照',
  `guard_observations_json` JSON NOT NULL COMMENT '保护指标观察结果',
  `external_interferences_json` JSON NOT NULL COMMENT '外部干扰声明',
  `stop_triggered` TINYINT(1) UNSIGNED NOT NULL DEFAULT 0 COMMENT '是否触发停止条件',
  `stop_evidence_refs_json` JSON NOT NULL COMMENT '停止条件证据引用',
  `comparison_json` JSON NOT NULL COMMENT '同口径比较与目标进度',
  `result_summary` VARCHAR(1000) NOT NULL COMMENT '系统三态判定摘要',
  `causality_claimed` TINYINT(1) UNSIGNED NOT NULL DEFAULT 0 COMMENT '固定为0，不宣称因果',
  `content_digest` CHAR(64) NOT NULL COMMENT '完整判定SHA-256摘要',
  `assessed_by` BIGINT UNSIGNED NOT NULL COMMENT '发起判定的用户ID',
  `assessed_at` DATETIME NOT NULL COMMENT '判定时间',
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uniq_operation_intervention_assessment_digest` (`tenant_id`, `hotel_id`, `task_id`, `content_digest`),
  KEY `idx_operation_intervention_assessment_task` (`tenant_id`, `hotel_id`, `intent_id`, `task_id`, `id`),
  KEY `idx_operation_intervention_assessment_verdict` (`tenant_id`, `hotel_id`, `verdict`, `id`),
  KEY `idx_operation_intervention_assessment_contract` (`tenant_id`, `intervention_contract_id`, `id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='经营干预三态学习判定追加账本';

